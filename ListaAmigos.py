# Lista (Nombre amigos)
nombres = ["Ana", "Luis", "Carlos", "Maria"]

print(nombres)

# Muestro el primer nombre
print(nombres[0])
print ("\n ---------------")

# Muestro el último amigo
print(nombres[-1])
print ("\n ---------------")

# Cambiar el segundo nombre
nombres[1] = "María"
print ("\n ---------------")

# Muestro la lista completa
print(nombres)
print ("\n ---------------")

